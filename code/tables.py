"""Generate the manuscript's data tables as LaTeX, from the experiments' JSON.

Tables that list per-level or per-rung numbers are generated rather than typed,
for the same reason the numbers are: so that the manuscript cannot disagree with
the artefact.
"""
from __future__ import annotations
import json, os, sys
import numpy as np

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import dataset as D
import simulator as S

OUTDIR = os.path.abspath(os.environ.get("PHYSICS_PAPER_DIR", os.path.join(D.RESULTS, "..", "paper")))


def load(name):
    p = os.path.join(D.RESULTS, name)
    return json.load(open(p)) if os.path.exists(p) else None


def w(name, text):
    with open(os.path.join(OUTDIR, name), "w") as f:
        f.write("%% Generated by code/tables.py -- do not edit.\n" + text)
    print(f"  -> {name}")


def fmt(v, p=2):
    if v is None or (isinstance(v, float) and not np.isfinite(v)):
        return "--"
    if abs(v) >= 1e4:
        return f"{v:.3g}"
    return f"{v:.{p}f}"


def tab_premise(e1):
    rows = []
    for r in e1["rungs"]:
        tag = r["rung"].split()[0]
        name = " ".join(r["rung"].split()[1:])
        beta = r["beta_summary"]
        rho, rq = r["rho"], r["rho_quadratic"]
        verdict = (r"\cmark" if r["admit_guess"] else r"\xmark")
        vr = (r"\cmark" if r["admit_randomised"] else r"\xmark")
        g = lambda v: (fmt(v, 3) if v < 100 else f"{v:.3g}")
        rows.append(f"{tag} & {name} & {r['n_params']} & {fmt(beta,3)} & "
                    f"{fmt(r['mu'],2)} & {fmt(r['tau'],2)} & "
                    f"{fmt(r['r_null'],3)} & {fmt(r['r_star'],3)} & "
                    f"{fmt(r['r_pi'],3)} & {g(rho)} & {g(rq)} & "
                    f"{verdict} & {vr} \\\\")
    body = "\n".join(rows)
    w("tab_premise.tex", rf"""
\begin{{table}}[t]\centering\small
\caption{{Rung by rung: oracle coefficient, prior, risks, and the knowledge
ratio in exact ($\rho$) and surrogate ($\rho_H$) form. Each row adds its
coefficient block while all lower-rung coefficients are fixed at their prior
means and $s=8$ dB. $\beta$ is the conditional optimum (standard deviation
across gateways for F3), $m$ and $\tau$ are its prior mean and standard deviation,
$R_0$ is the omitted-rung risk, $R^\star$ its conditional minimum, and
$\E_\pi R$ integrates only this rung. The last columns mark admission under a
prior draw in expectation and under the prior mean; \cmark{{}} admits. These
conditional optima differ from joint refits in Table~\ref{{tab:fits}}.}}
\label{{tab:premise}}
\begin{{tabular}}{{@{{}}llrrrr rrr rr cc@{{}}}}
\toprule
& Rung & \#coef. & $\beta$ & $m$ & $\tau$ & $R_0\downarrow$ & $R^\star\downarrow$ & $\E_\pi R\downarrow$ &
$\rho\downarrow$ & $\rho_H\downarrow$ & draw & rand. \\
\midrule
{body}
\bottomrule
\end{{tabular}}
\end{{table}}
""")


def tab_fits(e1):
    lad = e1["ladder"]
    rows = []
    for r in lad:
        tag = r["name"].split()[0]
        phi = np.array(r["phi"])
        n_gw = e1["n_gw"]
        rows.append(
            f"{tag} & {fmt(r['nll'],4)} & {fmt(r['sigma'],1)} & "
            f"{100*r['detection']:.2f} & {fmt(phi[0],1)} & "
            f"{fmt(2+phi[1],2)} & {fmt(phi[2:2+n_gw].std(),2)} & "
            f"{fmt(phi[2+n_gw],3)} & {fmt(phi[3+n_gw],5)} \\\\")
    body = "\n".join(rows)
    t = e1["tobit"]; l = e1["ls_received"]
    w("tab_fits.tex", rf"""
\begin{{table}}[t]\centering\small
\caption{{Censored maximum-likelihood fit of the ladder on \nCand{{}} candidate
links. Rows F1--F5 jointly refit every active coefficient and residual scale; F0
fixes the scale at 8 dB;
the last row instead uses least squares on received links only. Columns give
mean negative log-likelihood, residual scale $s$ (dB), predicted reception rate,
clutter $C$ (dB), path-loss exponent $n$, gateway-offset standard deviation (dB),
$\kappa$ (dB/occupied run), and $\gamma$ (dB/m). Reception rate and
coefficients are descriptive parameters, not metrics with an optimisation direction.}}
\label{{tab:fits}}
\begin{{tabular}}{{@{{}}lrrrrrrrr@{{}}}}
\toprule
& $-\log L\downarrow$ & $s$ (dB) & det.\ (\%) & $C$ (dB) & $n$ & sd $\delta_g$ &
$\kappa$ & $\gamma$ \\
\midrule
{body}
\midrule
received only & -- & {fmt(l['sigma'],1)} & -- & {fmt(l['C'],1)} &
{fmt(l['n'],2)} & {fmt(l['gw_sd'],2)} & {fmt(l['kappa'],3)} &
{fmt(l['gamma'],5)} \\
\bottomrule
\end{{tabular}}
\end{{table}}
""")


def tab_ladder(e2):
    lv = list(range(len(e2["levels"])))

    def pick(regime, mode, l):
        for r in e2["rows"]:
            if r["regime"] == regime and r["mode"] == mode and r["level"] == l:
                return r
        return None

    rows = []
    for l in lv:
        o = pick("uninformed", "oracle", l)
        g = pick("uninformed", "guess", l)
        rr = pick("uninformed", "randomised", l)
        i = pick("informed", "guess", l)
        tag = e2["levels"][l].split()[0]
        rows.append(
            f"{tag} & {fmt(o['nll'],4)} & {fmt(g['nll'],4)} & "
            f"{fmt(rr['nll'],4)} & {fmt(i['nll'],4)} & "
            f"{fmt(o['err50'],0)} & {fmt(g['err50'],0)} & "
            f"{fmt(rr['err50'],0)} & {fmt(i['err50'],0)} \\\\")
    body = "\n".join(rows)
    w("tab_ladder.tex", rf"""
\begin{{table}}[t]\centering\small
\caption{{The ladder on both tasks under four coefficient regimes; lower is
better throughout. Each row is a fidelity level. Oracle jointly refits active
coefficients and scale; draw averages 20 paired prior draws, including a draw of
$s$; rand. uses all prior means; survey averages 20 draws with informed gateway
offsets. Left columns score link likelihood; right columns score a simulated
fingerprint map. Oracle and survey use real calibration information; prior draw
and prior mean do not. The mean arm is a fixed simulator, not mixture training
of the nonlinear localizer. The real-only blocked five-fold baseline on 12,000 SF7 queries is
\SI{{{e2['ceiling']['err50']:.0f}}}{{\metre}}.}}
\label{{tab:ladder}}
\begin{{tabular}}{{@{{}}lrrrr@{{\hskip 14pt}}rrrr@{{}}}}
\toprule
& \multicolumn{{4}}{{c}}{{link task, $-\log L\downarrow$}} &
  \multicolumn{{4}}{{c}}{{localization, median error (m) $\downarrow$}} \\
\cmidrule(lr){{2-5}}\cmidrule(lr){{6-9}}
& oracle & draw & rand. & survey & oracle & draw & rand. & survey \\
\midrule
{body}
\bottomrule
\end{{tabular}}
\end{{table}}
""")


def tab_robust(e8):
    v = e8["loc_variants"]
    rows = []
    for name, r in v.items():
        errs = " & ".join(fmt(e, 0) for e in r["err"])
        rows.append(f"{name.replace('_',' ')} & {errs} & F{r['argmin']} \\\\")
    body = "\n".join(rows)
    ncol = len(next(iter(v.values()))["err"])
    heads = " & ".join(f"F{i} $\\downarrow$" for i in range(ncol))
    w("tab_robust.tex", rf"""
\begin{{table}}[t]\centering\small
\caption{{Median positioning error (m) along the ladder under every nuisance
choice and two alternative geometric priors. Rows identify the changed
protocol setting; columns F0--F5 report errors ($\downarrow$); argmin is the
lowest-error level. Each entry averages six paired coefficient draws, versus
20 in Table~\ref{{tab:ladder}}, explaining the different base row.}}
\label{{tab:robust}}
\begin{{tabular}}{{@{{}}l{'r'*ncol}c@{{}}}}
\toprule
variant & {heads} & argmin \\
\midrule
{body}
\bottomrule
\end{{tabular}}
\end{{table}}
""")


def main():
    for name, fn in (("exp1_premise.json", tab_premise),
                     ("exp1_premise.json", tab_fits),
                     ("exp2_ladder.json", tab_ladder),
                     ("exp8_robustness.json", tab_robust)):
        e = load(name)
        if e is None:
            print(f"  skip {fn.__name__}: {name} missing")
            continue
        try:
            fn(e)
        except Exception as exc:
            print(f"  FAILED {fn.__name__}: {exc}")


if __name__ == "__main__":
    main()
